-- Spec Q2, Q3, Data model. Both tables are versioned (Q7): changes go through saveWithVersion().

CREATE TABLE chore_types (
  id                 TEXT    PRIMARY KEY,
  type_key           TEXT    NOT NULL UNIQUE,   -- English slug
  short_label        TEXT    NOT NULL,          -- the picker tile
  full_label         TEXT    NOT NULL,          -- title / aria-label
  icon               TEXT    NOT NULL,          -- an emoji
  sort_order         INTEGER NOT NULL,
  archived_at        TEXT,                      -- out of the picker; past chores keep it
  update_count       INTEGER NOT NULL DEFAULT 0,
  created_at         TEXT    NOT NULL,
  updated_at         TEXT    NOT NULL,
  deleted_at         TEXT,
  deleted_by_user_id TEXT    REFERENCES users(id)
);

CREATE TABLE chores (
  id                 TEXT    PRIMARY KEY,       -- UUID v7 generated by the browser (Q20 point 1)
  chore_type_id      TEXT    NOT NULL REFERENCES chore_types(id),
  duration_minutes   INTEGER NOT NULL
    CHECK (duration_minutes % 15 = 0 AND duration_minutes BETWEEN 15 AND 1440),
  started_at         TEXT    NOT NULL,
  performer_user_id  TEXT    NOT NULL REFERENCES users(id),
  author_user_id     TEXT    NOT NULL REFERENCES users(id),  -- set by the server, never shown
  note               TEXT,
  update_count       INTEGER NOT NULL DEFAULT 0,
  created_at         TEXT    NOT NULL,
  updated_at         TEXT    NOT NULL,
  deleted_at         TEXT,
  deleted_by_user_id TEXT    REFERENCES users(id)
);
CREATE INDEX chores_performer_started_at ON chores (performer_user_id, started_at);
CREATE INDEX chores_started_at ON chores (started_at);

